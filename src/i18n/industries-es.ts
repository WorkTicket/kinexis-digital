export function localizeIndustry(industry: Industry, locale: Locale): Industry {
  if (locale === "en") return industry;
  const copy = ES[industry.slug];
  const merged: Industry = copy ? { ...industry, ...copy } : industry;
  return locale === "es-ES" ? spainizeData(merged) : merged;
}

export function localizedIndustries(locale: Locale): Industry[] {
  return INDUSTRIES.map((industry) => localizeIndustry(industry, locale));
}
