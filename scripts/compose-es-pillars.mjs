/**
 * Builds Spanish pillar bodies from EN structure + native Spanish core paragraphs.
 * Run: npx tsx scripts/compose-es-pillars.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PILLAR_POSTS } from "../src/data/pillar-posts.ts";
import { PILLAR_POSTS_MORE } from "../src/data/pillar-posts-more.ts";
import { ES_PILLAR_META } from "./es-pillars-meta.mjs";
import { ES_CORE } from "./es-pillars-core/bundled.mjs";

const EN = { ...PILLAR_POSTS, ...PILLAR_POSTS_MORE };
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "scripts/es-pillars-payload.mjs");

function toHtml(paragraphs) {
  return paragraphs.map((t) => `<p>${t}</p>`).join("");
}

const SLUGS = Object.keys(ES_PILLAR_META);

const POSTS = {};
for (const slug of SLUGS) {
  const en = EN[slug];
  const meta = ES_PILLAR_META[slug];
  const core = ES_CORE[slug];
  if (!en || !core) throw new Error(`Missing EN or ES_CORE for ${slug}`);
  const sections = en.sections.map((sec, i) => {
    const c = core.sections[i];
    if (!c) throw new Error(`Missing ES_CORE section ${i} for ${slug}`);
    return {
      h2: c.h2,
      html: toHtml(c.paragraphs),
    };
  });
  POSTS[slug] = {
    slug,
    ...meta,
    lead: core.lead,
    sections,
  };
}

const file = `/** Auto-generated by compose-es-pillars.mjs — do not edit by hand. */\nexport const POSTS = ${JSON.stringify(POSTS, null, 2)};\n`;
writeFileSync(out, file, "utf8");
console.log("Wrote", out, Object.keys(POSTS).length, "posts");
